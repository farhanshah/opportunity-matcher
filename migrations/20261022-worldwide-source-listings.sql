-- Source-confirmed worldwide programmes. No automatic eligibility matching.
-- Strict opportunities table remains reserved for fully verified records.
CREATE TABLE IF NOT EXISTS worldwide_source_listings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 canonical_url text NOT NULL UNIQUE,
 provider text NOT NULL,
 title text NOT NULL,
 evidence_hash text NOT NULL,
 source_status text NOT NULL DEFAULT 'source_confirmed'
   CHECK (source_status IN ('source_confirmed','unavailable','superseded')),
 verified_page_at timestamptz NOT NULL,
 last_checked_at timestamptz NOT NULL DEFAULT now(),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
 linked_opportunity_id uuid REFERENCES opportunities(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS worldwide_source_listings_public_idx
 ON worldwide_source_listings(source_status,verified_page_at DESC)
 WHERE source_status='source_confirmed';
